#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn lang_roundtrip() {
        assert_eq!(Lang::from_code("es"), Lang::Es);
        assert_eq!(Lang::from_code("en"), Lang::En);
        assert_eq!(Lang::from_code("English"), Lang::En);
        assert_eq!(Lang::from_code("unknown"), Lang::Es);
        assert_eq!(Lang::Es.code(), "es");
    }

    #[test]
    fn all_keys_have_es_and_en() {
        for k in all_keys() {
            let es = t(Lang::Es, k);
            let en = t(Lang::En, k);
            assert!(!es.is_empty(), "{k:?} es empty");
            assert!(!en.is_empty(), "{k:?} en empty");
        }
    }
}
